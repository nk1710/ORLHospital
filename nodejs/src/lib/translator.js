const RTL_LANGUAGES = ["ar", "ur", "fa"];

/**
 * Recursively translates text nodes across the given root element
 */
function translateDOM(root, dict) {
  if (!root || !dict) return;

  const walker = document.createTreeWalker(
    root,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode(node) {
        if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        const parent = node.parentElement;
        if (!parent) return NodeFilter.FILTER_REJECT;
        const tag = parent.tagName.toLowerCase();
        if (tag === "script" || tag === "style" || tag === "noscript" || tag === "svg") {
          return NodeFilter.FILTER_REJECT;
        }
        // Don't translate inside language selector itself
        if (parent.closest("[data-no-translate]")) {
          return NodeFilter.FILTER_REJECT;
        }
        return NodeFilter.FILTER_ACCEPT;
      }
    }
  );

  const textNodes = [];
  while (walker.nextNode()) {
    textNodes.push(walker.currentNode);
  }

  for (const node of textNodes) {
    const parent = node.parentElement;
    if (!parent) continue;

    // Cache original English text on the parent element
    if (!parent.hasAttribute("data-orig-text")) {
      parent.setAttribute("data-orig-text", node.nodeValue);
    }

    const orig = parent.getAttribute("data-orig-text");
    let replaced = orig;

    // Check exact matches or phrase replacements
    for (const [enPhrase, targetPhrase] of Object.entries(dict)) {
      if (replaced.includes(enPhrase)) {
        replaced = replaced.replaceAll(enPhrase, targetPhrase);
      }
    }

    if (replaced !== node.nodeValue) {
      node.nodeValue = replaced;
    }
  }
}

/**
 * Restores original English text on all previously translated elements
 */
function restoreEnglish(root) {
  if (!root) return;
  const elements = root.querySelectorAll("[data-orig-text]");
  elements.forEach((el) => {
    const orig = el.getAttribute("data-orig-text");
    if (orig) {
      el.textContent = orig;
      el.removeAttribute("data-orig-text");
    }
  });
}

/**
 * Applies the selected language across the entire document
 */
export function applyLanguage(langCode) {
  if (typeof window === "undefined" || typeof document === "undefined") return;

  try {
    localStorage.setItem("orl_preferred_lang", langCode);
  } catch (e) {}

  const isRtl = RTL_LANGUAGES.includes(langCode);
  document.documentElement.lang = langCode;
  document.documentElement.dir = isRtl ? "rtl" : "ltr";

  if (langCode === "en") {
    restoreEnglish(document.body);
    return;
  }

  const dict = TRANSLATIONS[langCode];
  if (!dict) return;

  // Restore English first to clean baseline before applying new translation
  restoreEnglish(document.body);
  translateDOM(document.body, dict);
}

/**
 * Retrieves initial preferred language from localStorage or browser
 */
export function getStoredLanguage() {
  if (typeof window === "undefined") return "en";
  try {
    const saved = localStorage.getItem("orl_preferred_lang");
    if (saved && LANGUAGES.some((l) => l.code === saved)) {
      return saved;
    }
  } catch (e) {}
  return "en";
}
